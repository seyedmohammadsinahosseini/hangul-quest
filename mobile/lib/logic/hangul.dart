/// Unicode maths for Hangul syllable composition (U+AC00 block).
library;

const List<String> _initials = [
  'ㄱ', 'ㄲ', 'ㄴ', 'ㄷ', 'ㄸ', 'ㄹ', 'ㅁ', 'ㅂ', 'ㅃ', 'ㅅ', 'ㅆ', 'ㅇ', 'ㅈ', 'ㅉ', 'ㅊ', 'ㅋ', 'ㅌ', 'ㅍ', 'ㅎ',
];
const List<String> _medials = [
  'ㅏ', 'ㅐ', 'ㅑ', 'ㅒ', 'ㅓ', 'ㅔ', 'ㅕ', 'ㅖ', 'ㅗ', 'ㅘ', 'ㅙ', 'ㅚ', 'ㅛ', 'ㅜ', 'ㅝ', 'ㅞ', 'ㅟ', 'ㅠ', 'ㅡ', 'ㅢ', 'ㅣ',
];
const List<String> _finals = [
  '', 'ㄱ', 'ㄲ', 'ㄳ', 'ㄴ', 'ㄵ', 'ㄶ', 'ㄷ', 'ㄹ', 'ㄺ', 'ㄻ', 'ㄼ', 'ㄽ', 'ㄾ', 'ㄿ', 'ㅀ', 'ㅁ', 'ㅂ', 'ㅄ', 'ㅅ', 'ㅆ', 'ㅇ', 'ㅈ', 'ㅊ', 'ㅋ', 'ㅌ', 'ㅍ', 'ㅎ',
];

/// Live-compose jamo pieces into a real syllable block, e.g. [ㅎ, ㅏ, ㄴ] -> 한.
String composeSyllable(List<String> pieces) {
  if (pieces.isEmpty) return '';
  final i = _initials.indexOf(pieces[0]);
  final m = pieces.length > 1 ? _medials.indexOf(pieces[1]) : -1;
  if (i < 0 || m < 0) return pieces.join();
  var f = 0;
  if (pieces.length > 2) {
    f = _finals.indexOf(pieces[2]);
    if (f < 0) return pieces.join();
  }
  return String.fromCharCode(0xAC00 + (i * 21 + m) * 28 + f);
}

